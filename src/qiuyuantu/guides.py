def table(head: list[str], rows: list[list[str]], note: str = "") -> str:
    """正文里的数据表。数字列（以数字开头的格子）用等宽字体；note 是表下的一行小字（数据来源）。"""

    def cell(v: str) -> str:
        return f'<td class="n">{v}</td>' if v[:1].isdigit() else f"<td>{v}</td>"

    body = "".join("<tr>" + "".join(cell(v) for v in r) + "</tr>" for r in rows)
    html = f'<div class="tbl"><table><tr>{"".join(f"<th>{h}</th>" for h in head)}</tr>{body}</table></div>'
    return html + (f'<p class="note">{note}</p>' if note else "")


